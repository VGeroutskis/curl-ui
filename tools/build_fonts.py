#!/usr/bin/env python3
"""Subset the UI fonts and embed them as C arrays: src/ui/fonts_data.{c,h}.

IBM Plex Mono has no Greek, so a DejaVu Sans Mono subset holding exactly the
glyphs Plex lacks is merged into it here, scaled to Plex's units per em and
snapped to its advance so the monospace grid stays exact. (Merging at atlas
time is not an option: Nuklear's merge_mode only ever targets the first font.)
Each font also gets its real codepoint ranges for baking.

Requires: pip install fonttools brotli
Usage: build_fonts.py [--fonts DIR] [--out DIR]
"""
import argparse
import io
import os

from fontTools import subset
from fontTools.merge import Merger
from fontTools.ttLib import TTFont
from fontTools.ttLib.scaleUpem import scale_upem

HERE = os.path.dirname(os.path.abspath(__file__))

WANTED = sorted(set(
    list(range(0x20, 0x7F)) + list(range(0xA0, 0x180)) +       # Latin
    list(range(0x370, 0x400)) + list(range(0x400, 0x500)) +    # Greek, Cyrillic
    list(range(0x2010, 0x2028)) + list(range(0x2030, 0x203B)) +  # punctuation
    [0x20AC, 0x2122, 0x2190, 0x2191, 0x2192, 0x2193, 0x2212, 0x2260, 0x2264,
     0x2265, 0x2713, 0x2717, 0x25B8, 0x25BE, 0x2022, 0xFFFD]))

FONTS = [
    ("plex_sans_regular", "IBMPlexSans-Regular.woff2", None),
    ("plex_sans_semibold", "IBMPlexSans-SemiBold.woff2", None),
    ("plex_mono_regular", "IBMPlexMono-Regular.woff2", "DejaVuSansMono.ttf"),
    ("plex_mono_semibold", "IBMPlexMono-SemiBold.woff2", "DejaVuSansMono-Bold.ttf"),
]


def make_subset(path, codepoints):
    font = TTFont(path)
    options = subset.Options()
    options.hinting = False
    options.layout_features = []
    options.notdef_outline = True
    options.name_IDs = [1, 2]
    options.drop_tables += ["GSUB", "GPOS", "GDEF", "DSIG", "FFTM"]
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font)
    font.flavor = None
    out = io.BytesIO()
    font.save(out)
    return out.getvalue()


def merge_missing(base_bytes, extra_path, missing):
    """Adds the `missing` glyphs of a TrueType font to the base subset."""
    base = TTFont(io.BytesIO(base_bytes))
    upem = base["head"].unitsPerEm
    advance = base["hmtx"]["space"][0]
    extra = TTFont(io.BytesIO(make_subset(extra_path, missing)))
    scale_upem(extra, upem)
    for glyph in extra.getGlyphOrder():
        width, lsb = extra["hmtx"][glyph]
        extra["hmtx"][glyph] = (advance, lsb + (advance - width) // 2)
    # the merger keeps the first font's vertical metrics
    tables = []
    for font in (base, extra):
        out = io.BytesIO()
        font.save(out)
        out.seek(0)
        tables.append(out)
    merged = Merger().merge(tables)
    out = io.BytesIO()
    merged.save(out)
    return out.getvalue()


def ranges(codepoints):
    result = []
    for cp in sorted(codepoints):
        if result and result[-1][1] == cp - 1:
            result[-1][1] = cp
        else:
            result.append([cp, cp])
    return result


def emit(c, h, name, data, cps):
    c.append("const unsigned char %s_ttf[] = {" % name)
    for i in range(0, len(data), 20):
        c.append(",".join(str(b) for b in data[i:i + 20]) + ",")
    c.append("};")
    c.append("const unsigned int %s_ttf_len = %d;" % (name, len(data)))
    flat = [v for pair in ranges(cps) for v in pair] + [0]
    c.append("const unsigned int %s_ranges[] = {%s};\n" % (name, ",".join(map(str, flat))))
    h.append("extern const unsigned char %s_ttf[];" % name)
    h.append("extern const unsigned int %s_ttf_len;" % name)
    h.append("extern const unsigned int %s_ranges[];" % name)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fonts", default=os.path.join(HERE, "..", "assets", "fonts"))
    ap.add_argument("--out", default=os.path.join(HERE, "..", "src", "ui"))
    args = ap.parse_args()

    c = ["/* GENERATED by tools/build_fonts.py. Do not edit. */", '#include "fonts_data.h"', ""]
    h = ["/* GENERATED by tools/build_fonts.py. Do not edit. */",
         "#ifndef CURLUI_FONTS_DATA_H", "#define CURLUI_FONTS_DATA_H", ""]
    for name, fname, extra in FONTS:
        path = os.path.join(args.fonts, fname)
        have = set(TTFont(path).getBestCmap()) & set(WANTED)
        data = make_subset(path, have)
        note = ""
        if extra:
            extra_path = os.path.join(args.fonts, extra)
            missing = (set(TTFont(extra_path).getBestCmap()) & set(WANTED)) - have
            data = merge_missing(data, extra_path, missing)
            have |= missing
            note = " (%d merged from %s)" % (len(missing), extra)
        emit(c, h, name, data, have)
        print("%-20s %6d bytes, %d glyphs%s" % (name, len(data), len(have), note))
    h += ["", "#endif"]
    with open(os.path.join(args.out, "fonts_data.c"), "w", newline="\n") as f:
        f.write("\n".join(c) + "\n")
    with open(os.path.join(args.out, "fonts_data.h"), "w", newline="\n") as f:
        f.write("\n".join(h) + "\n")


if __name__ == "__main__":
    main()
